"""Adds the client's languages to the person forms (create and edit), from the registry in
shared/languages/languages.json, so the choice list can never drift from what the SMS and voice code
understands.

Fields, placed after the phone numbers:
  preferred_language        the language the person speaks best (required)
  preferred_language_other  which one, if it is not on the list
  other_languages           other languages they understand (space-separated codes)

The SMS reminders and voice replies use these to choose the client's language, and only ever a
language listed here for that person (shared/languages/index.js). The registry orders the list:
the pilot language first, then each region's main languages, then the others, then English.

It also writes cht-app/language-names.js, the code-to-name map the profile uses.

Run from cht-app/: python tools/build_language_fields.py
then:              npx cht --no-check convert-contact-forms -- person-create person-edit
"""
import json
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "shared" / "languages" / "languages.json"
FORMS = [ROOT / "cht-app" / "forms" / "contact" / f"{n}.xlsx" for n in ("person-create", "person-edit")]
NAMES_JS = ROOT / "cht-app" / "language-names.js"
FIELDS = ("preferred_language", "preferred_language_other", "other_languages")
LIST = "language"
AFTER = "phone_alternate"


def language_choices():
    langs = json.loads(REGISTRY.read_text(encoding="utf-8"))["languages"]

    def label(code):
        lang = langs[code]
        aliases = [a for a in lang.get("aliases", []) if len(a) > 3 and a.lower() != lang["name"].lower()]
        return f"{lang['name']} ({aliases[0]})" if aliases and "(" not in lang["name"] else lang["name"]

    codes = sorted((c for c in langs if c != "en"), key=lambda c: (langs[c]["tier"], langs[c]["name"]))
    return [(c, label(c)) for c in codes] + [("en", "English"), ("other", "Other (write it in)")]


def survey_rows():
    return [
        {"type": f"select_one {LIST}", "name": "preferred_language",
         "label::en": "Which language does this person speak best?", "required": "yes", "appearance": "minimal",
         "hint::en": "Reminders and voice replies use this language once a checked translation exists; "
                     "until then they are in English."},
        {"type": "string", "name": "preferred_language_other", "label::en": "Which language?",
         "required": "yes", "relevant": "selected(${preferred_language},'other')"},
        {"type": f"select_multiple {LIST}", "name": "other_languages",
         "label::en": "Other languages this person understands", "appearance": "minimal",
         "hint::en": "Used only if their own language has no checked message yet. Leave empty if none."},
    ]


def _write_row(ws, idx, header, values):
    ws.insert_rows(idx)
    for col, name in enumerate(header, start=1):
        if name in values:
            ws.cell(row=idx, column=col, value=values[name])


def update(path):
    wb = openpyxl.load_workbook(path)
    survey, choices = wb["survey"], wb["choices"]
    s_head = [c.value for c in survey[1]]
    c_head = [c.value for c in choices[1]]
    name_col = s_head.index("name") + 1

    # Idempotent: remove what an earlier run added, then add it again.
    for r in range(survey.max_row, 1, -1):
        if survey.cell(row=r, column=name_col).value in FIELDS:
            survey.delete_rows(r)
    for r in range(choices.max_row, 1, -1):
        if choices.cell(row=r, column=1).value == LIST:
            choices.delete_rows(r)

    anchor = next(r for r in range(2, survey.max_row + 1) if survey.cell(row=r, column=name_col).value == AFTER)
    for i, values in enumerate(survey_rows(), start=1):
        _write_row(survey, anchor + i, s_head, values)

    last = max(r for r in range(1, choices.max_row + 1) if any(c.value not in (None, "") for c in choices[r]))
    for i, (code, label) in enumerate(language_choices(), start=1):
        _write_row(choices, last + i, c_head, {"list_name": LIST, "name": code, "label::en": label})
    wb.save(path)


def write_names_js():
    """The profile shows the language by name; the app bundle gets a small generated map, not the registry."""
    def js_string(text):  # the app's eslint wants single quotes
        return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"

    lines = [f"  {code}: {js_string(label)}," for code, label in language_choices() if code != "other"]
    header = "// Generated by tools/build_language_fields.py from shared/languages/languages.json. Do not edit."
    NAMES_JS.write_bytes(("\n".join([header, "module.exports = {", *lines, "};"]) + "\n").encode("utf-8"))


if __name__ == "__main__":
    for form in FORMS:
        update(form)
        print(f"updated {form.name}")
    write_names_js()
    print(f"wrote {NAMES_JS.name}")
